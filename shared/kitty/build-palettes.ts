#!/usr/bin/env bun
// build-palettes.ts — post-process the vendored palettes in themes/*.conf.
//
//   bun ~/dotfiles/shared/kitty/build-palettes.ts     (idempotent; rerun after adding a theme)
//
// Light themes (background luminance > 0.5):
//   * Darkens any ANSI text color (color1-15) in OKLCH, keeping hue, until it
//     reaches MIN_CONTRAST against the background and MIN_SELECTION_CONTRAST
//     against selection_background. Upstream light palettes ship pastel accents
//     (e.g. yellow ~2:1) that are unreadable as text.
//   * Generates color16-255 from the theme's own colors: the 6x6x6 cube is a
//     trilinear blend of bg/red/green/yellow/blue/magenta/cyan/fg and the
//     232-255 grey ramp runs bg -> fg. Without this, apps that paint 256-color
//     greys (236, 237, ...) leave dark patches on a light background.
// Dark themes: fills any color16-255 the conf doesn't set with the stock xterm
// values, so switching light -> dark restores the standard 256-color palette.

import { Glob } from "bun";

const MIN_CONTRAST = 4.5; // WCAG AA, accents + muted/fg text
const MIN_DIM_CONTRAST = 4.0; // color8: dim (autosuggestions, comments) but readable
const MIN_SELECTION_CONTRAST = 3.0;
const MARKER = "# --- color16-255: generated by ../build-palettes.ts, do not edit below ---";

type RGB = [number, number, number];

const hexToRgb = (h: string): RGB => {
  const n = parseInt(h.replace("#", ""), 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
};
const rgbToHex = (c: RGB) =>
  "#" + c.map((v) => Math.round(Math.min(255, Math.max(0, v))).toString(16).padStart(2, "0")).join("");

const toLinear = (v: number) => ((v /= 255) <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4);
const fromLinear = (v: number) => 255 * (v <= 0.0031308 ? 12.92 * v : 1.055 * v ** (1 / 2.4) - 0.055);

const luminance = (c: RGB) => {
  const [r, g, b] = c.map(toLinear);
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const contrast = (a: RGB, b: RGB) => {
  const [x, y] = [luminance(a), luminance(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
};

// OKLab (Björn Ottosson)
type Lab = [number, number, number];
const toOklab = (c: RGB): Lab => {
  const [r, g, b] = c.map(toLinear);
  const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b);
  const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b);
  const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b);
  return [
    0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s,
    1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s,
    0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s,
  ];
};
const fromOklab = ([L, a, b]: Lab): RGB => {
  const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s = (L - 0.0894841775 * a - 1.291485548 * b) ** 3;
  return [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ].map((v) => fromLinear(Math.min(1, Math.max(0, v)))) as RGB;
};
const mix = (a: Lab, b: Lab, t: number): Lab => [0, 1, 2].map((i) => a[i] + (b[i] - a[i]) * t) as Lab;

// Lower OKLab lightness (hue/chroma kept) until every constraint holds.
const darkenUntil = (hex: string, against: [RGB, number][]): string => {
  let lab = toOklab(hexToRgb(hex));
  let rgb = hexToRgb(hex);
  while (against.some(([bg, min]) => contrast(rgb, bg) < min) && lab[0] > 0) {
    lab = [lab[0] - 0.005, lab[1], lab[2]];
    rgb = fromOklab(lab);
  }
  return rgbToHex(rgb);
};

const xterm = (i: number): string => {
  if (i >= 232) {
    const v = 8 + 10 * (i - 232);
    return rgbToHex([v, v, v]);
  }
  const n = i - 16;
  const lvl = (k: number) => (k === 0 ? 0 : 55 + 40 * k);
  return rgbToHex([lvl(Math.floor(n / 36)), lvl(Math.floor(n / 6) % 6), lvl(n % 6)]);
};

const keyRe = /^\s*(\S+)\s+(\S+)/;
const isHighColor = (k: string) => /^color(\d+)$/.test(k) && +k.slice(5) >= 16;

const themesDir = `${import.meta.dir}/themes`;
for await (const file of new Glob("*.conf").scan(themesDir)) {
  const path = `${themesDir}/${file}`;
  const text = await Bun.file(path).text();
  let lines = text.split("\n");
  const cut = lines.indexOf(MARKER);
  if (cut >= 0) lines = lines.slice(0, cut);
  while (lines.length && lines.at(-1)!.trim() === "") lines.pop();

  const val = (k: string) => {
    for (const l of lines) {
      const m = l.match(keyRe);
      if (m && m[1] === k) return m[2];
    }
  };
  const bgHex = val("background")!;
  const fgHex = val("foreground")!;
  const bg = hexToRgb(bgHex);
  const light = luminance(bg) > 0.5;
  const generated: string[] = [];

  if (light) {
    const sel = val("selection_background");
    const selRgb = sel && sel.startsWith("#") ? hexToRgb(sel) : undefined;
    lines = lines
      .filter((l) => !isHighColor(l.match(keyRe)?.[1] ?? ""))
      .map((l) => {
        const m = l.match(keyRe);
        if (!m || !/^color([1-9]|1[0-5])$/.test(m[1])) return l;
        const min = m[1] === "color8" ? MIN_DIM_CONTRAST : MIN_CONTRAST;
        const constraints: [RGB, number][] = [[bg, min]];
        if (selRgb) constraints.push([selRgb, MIN_SELECTION_CONTRAST]);
        const tuned = darkenUntil(m[2], constraints);
        return tuned === m[2].toLowerCase() ? l : l.replace(m[2], tuned);
      });

    const c = (n: number) => toOklab(hexToRgb(val(`color${n}`)!));
    const B = toOklab(bg), F = toOklab(hexToRgb(fgHex));
    // corners indexed by (r,g,b) bits: 000 bg, 100 red, 010 green, 110 yellow, 001 blue, 101 magenta, 011 cyan, 111 fg
    const corner = (r: number, g: number, b: number) =>
      [[B, c(4)], [c(2), c(6)], [c(1), c(5)], [c(3), F]][r * 2 + g][b];
    for (let r = 0; r < 6; r++)
      for (let g = 0; g < 6; g++)
        for (let b = 0; b < 6; b++) {
          const [tr, tg, tb] = [r / 5, g / 5, b / 5];
          const lerpB = (rr: number, gg: number) => mix(corner(rr, gg, 0), corner(rr, gg, 1), tb);
          const p = mix(mix(lerpB(0, 0), lerpB(0, 1), tg), mix(lerpB(1, 0), lerpB(1, 1), tg), tr);
          generated.push(`color${16 + 36 * r + 6 * g + b} ${rgbToHex(fromOklab(p))}`);
        }
    for (let i = 0; i < 24; i++) generated.push(`color${232 + i} ${rgbToHex(fromOklab(mix(B, F, (i + 1) / 25)))}`);

    // report
    const report = [...Array(15)].map((_, i) => {
      const hex = val(`color${i + 1}`)!;
      return `c${i + 1}=${contrast(hexToRgb(hex), bg).toFixed(1)}`;
    });
    console.log(`${file} (light): ${report.join(" ")}`);
  } else {
    const defined = new Set(lines.map((l) => l.match(keyRe)?.[1]).filter(Boolean));
    for (let i = 16; i < 256; i++) if (!defined.has(`color${i}`)) generated.push(`color${i} ${xterm(i)}`);
    console.log(`${file} (dark): filled ${generated.length} stock xterm colors`);
  }

  await Bun.write(path, [...lines, "", MARKER, ...generated, ""].join("\n"));
}
